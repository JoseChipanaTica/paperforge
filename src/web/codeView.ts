import type { PytorchArtifact } from "../shared/learn";
import { escapeHtml } from "./scene";

/** The PyTorch tab: generated code linked both ways to the 3D blocks. */

/** Render the PyTorch artifact; clicking a line that implements a block calls onSymbol(blockId). */
export function showCode(panel: HTMLElement, artifact: PytorchArtifact, onSymbol: (blockId: string) => void) {
  // First line mentioning each symbol as a whole word marks where its block lives.
  const codeLines = artifact.code.split("\n");
  const lineBlock = new Map<number, string>();
  for (const { block_id, symbol } of artifact.block_map) {
    const re = new RegExp(`\\b${symbol.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`);
    const i = codeLines.findIndex((l, n) => re.test(l) && !lineBlock.has(n));
    if (i >= 0) lineBlock.set(i, block_id);
  }
  panel.hidden = false;
  panel.innerHTML = `
    <div class="code-head">
      <b>${escapeHtml(artifact.filename)}</b>
      <span>
        <button data-code="copy">Copy</button>
        <button data-code="download">Download</button>
        <button data-code="close" title="Close">×</button>
      </span>
    </div>
    <p class="code-note">Generated by Claude, not executed. Click a highlighted line to find its block.</p>
    <pre class="code-body">${codeLines
      // Lines are display:block, so no "\n" between them; a space keeps blank lines from collapsing.
      .map((l, i) =>
        lineBlock.has(i)
          ? `<span class="ln mapped" data-block="${escapeHtml(lineBlock.get(i)!)}">${escapeHtml(l) || " "}</span>`
          : `<span class="ln">${escapeHtml(l) || " "}</span>`,
      )
      .join("")}</pre>
    ${artifact.notes.length ? `<ul class="code-notes">${artifact.notes.map((n) => `<li>${escapeHtml(n)}</li>`).join("")}</ul>` : ""}`;

  panel.onclick = (e) => {
    const target = e.target as HTMLElement;
    const action = target.closest<HTMLElement>("button")?.dataset.code;
    if (action === "copy") void navigator.clipboard?.writeText(artifact.code).catch(() => {});
    else if (action === "download") {
      const url = URL.createObjectURL(new Blob([artifact.code], { type: "text/x-python" }));
      const a = Object.assign(document.createElement("a"), { href: url, download: artifact.filename });
      a.click();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    } else if (action === "close") panel.hidden = true;
    const line = target.closest<HTMLElement>(".ln.mapped");
    if (line?.dataset.block) onSymbol(line.dataset.block);
  };
}

/** Scroll the code panel to the line implementing a block, if any. */
export function revealSymbol(panel: HTMLElement, blockId: string) {
  const line = panel.querySelector<HTMLElement>(`.ln[data-block="${CSS.escape(blockId)}"]`);
  panel.querySelectorAll(".ln.lit").forEach((l) => l.classList.remove("lit"));
  if (!line) return;
  line.classList.add("lit");
  line.scrollIntoView({ block: "center", behavior: "smooth" });
}
